import csv from 'csvtojson';
import fs from 'node:fs';

const __dirname = import.meta.dirname;

const FG_FILE = ['fangraphs/fangraphs-game-log-dylan-cease.csv'];
const FORMATS_SOURCE = 'exports/averages-full.csv'; // Format column -> chart order - this is the all years averages google sheet
const DATE_FORMAT_MAP = 'exports/formats.csv'; // Date, Format
const OUTPUT_FILE = 'fangraphs';

const abs = (p) => `${__dirname}/${p}`;
const clean = (v) => String(v ?? '').trim(); // strip CRLF / stray whitespace

// Test for YYYY-MM-DD
function normalizeDate(raw) {
  const s = clean(raw);
  if (/^\d{4}-\d{2}-\d{2}$/.test(s)) return s;
  throw new Error(
    `Unrecognized date "${raw}" in ${DATE_FORMAT_MAP} (expected YYYY-MM-DD)`
  );
}

async function main() {
  // This works fine if we use DATE_FORMAT_MAP but the FORMATS_SOURCE gives us the right ordering.
  // Until we set that ourselves, use the extra file.
  const formatRows = await csv({ includeColumns: /Format/ }).fromFile(
    abs(FORMATS_SOURCE)
  );

  const formats = [];

  for (const row of formatRows) {
    const f = clean(row['Format']);
    if (!f) break; // blank row => end of the real table
    formats.push(f);
  }

  const validFormats = new Set(formats);

  // Date to format map. Throw on bad data in case there's a typo (this stuff is still in flux)
  const mapRows = await csv().fromFile(abs(DATE_FORMAT_MAP));
  const dateToFormat = new Map();
  for (const row of mapRows) {
    if (!clean(row['Date'])) continue;
    const date = normalizeDate(row['Date']);
    const format = clean(row['Format']);
    if (!validFormats.has(format)) {
      throw new Error(
        `Unknown format "${format}" for ${date}. Expected one of: ${formats.join(', ')}`
      );
    }
    if (dateToFormat.has(date)) {
      throw new Error(`Date ${date} appears twice in ${DATE_FORMAT_MAP}`);
    }
    dateToFormat.set(date, format);
  }

  const acc = {}; // acc[format] = { sum, count }

  await csv({ includeColumns: /Date|Stuff+/ })
    .fromFile(abs(FG_FILE))
    .subscribe((row) => {
      const date = row.Date;

      const format = dateToFormat.get(date);
      if (!format) {
        return;
      }

      const stuff = +row['Stuff+'];

      // There isn't any Stuff+ for 2019 so we expect this sometimes
      if (stuff === null || Number.isNaN(stuff)) return;

      acc[format] ??= { sum: 0, count: 0 };
      acc[format].sum += stuff;
      acc[format].count += 1;

      return acc;
    });

  const stuffs = formats.map((format) => {
    const cell = acc[format];
    console.log(format, cell, (cell.sum / cell.count).toFixed(2));
    return cell && cell.count > 0
      ? Number((cell.sum / cell.count).toFixed(2))
      : null;
  });

  const output = `// Generated by buildFangraphsData.js from FG Advanced Pitching game log export. Do not edit by hand.
    
export const stuffs = ${JSON.stringify(stuffs, null, 2)} as const;
    `;

  fs.writeFileSync(abs(`${OUTPUT_FILE}.ts`), output);
}

main();
