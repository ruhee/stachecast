import csv from 'csvtojson';
import fs from 'node:fs';
const __dirname = import.meta.dirname;

const csvFilePath = `${__dirname}/averages.csv`;

// Column headers in the Averages spreadsheet
const COLUMNS = [
  'Format',
  '4 seam',
  'Sinker',
  'Slider',
  'Sweeper',
  'Change',
  'Knuckle curve',
  'Game score',
  'K/9',
].join('|');

// Get this from the csv eventually
const FORMATS = [
  'Clean shaven',
  'Stache only',
  'Stache + soul patch',
  'Short beard',
  'Full beard',
  'Long beard',
  'Mountain man beard',
];

csv({
  includeColumns: new RegExp(COLUMNS),
})
  .fromFile(csvFilePath)
  .then((rows) => {
    const series = Object.keys(rows[0]).filter((key) => key !== 'Format');
    const finalObj = Object.fromEntries(series.map((name) => [name, []]));

    FORMATS.forEach((format) => {
      const row = rows.find((item) => item['Format'] === format);

      if (!row) {
        console.error(`Failed to save ${format}`);
      }

      series.forEach((name) => {
        const value = row?.[name];
        // Empty cells become null so chart.js leaves a gap instead of drawing 0
        finalObj[name].push(value ? Number(value) : null);
      });
    });

    const output = `// Generated by convertCsv.js from averages.csv. Do not edit by hand.

export const formats = ${JSON.stringify(FORMATS, null, 2)} as const;

export const averages = ${JSON.stringify(finalObj, null, 2)} as const;
`;

    fs.writeFileSync(`${__dirname}/averages.ts`, output);
    console.log('Saved file averages.ts');
  })
  .catch((err) => {
    console.log(err);
  });
