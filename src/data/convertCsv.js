import csv from 'csvtojson';
import fs from 'node:fs';
const __dirname = import.meta.dirname;

const isNew = !!process.env.npm_config_new;

// Switch based on the flag, so we can process both files in the same script.
// averages-full is all years, averages is just 2026 (switch these names later)
const fileName = isNew ? 'averages-full' : 'averages';
const csvFilePath = `${__dirname}/${fileName}.csv`;

// Column headers in the Averages spreadsheet
const COLUMNS = [
  'Format',
  '4 seam',
  'Sinker',
  'Slider',
  'Sweeper',
  'Change',
  'Knuckle curve',
  'Game score',
  'Game score max',
  'K/9',
].join('|');

csv({
  includeColumns: new RegExp(COLUMNS),
})
  .fromFile(csvFilePath)
  .then((rows) => {
    // Formats are in spreadsheet row order; skip any blank rows
    const formatRows = rows.filter((row) => row['Format']);
    const formats = formatRows.map((row) => row['Format']);

    const series = Object.keys(rows[0]).filter((key) => key !== 'Format');
    const finalObj = Object.fromEntries(
      series.map((name) => [
        name,
        // Empty cells become null so chart.js leaves a gap instead of drawing 0
        formatRows.map((row) => (row[name] ? Number(row[name]) : null)),
      ])
    );

    const output = `// Generated by convertCsv.js from ${fileName}.csv. Do not edit by hand.

export const formats = ${JSON.stringify(formats, null, 2)} as const;

export const averages = ${JSON.stringify(finalObj, null, 2)} as const;
`;

    fs.writeFileSync(`${__dirname}/${fileName}.ts`, output);
    console.log(`Saved file ${fileName}.ts`);
  })
  .catch((err) => {
    console.log(err);
  });
